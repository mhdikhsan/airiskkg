def local(term) -> str:
    return re.split(r"[#/]", str(term))[-1]


def clean(value) -> str:
    return " ".join(str(value).split()).replace("|", "\\|")


def one(graph: Graph, subject, *predicates):
    for predicate in predicates:
        values = sorted(graph.objects(subject, predicate), key=str)
        if values:
            return values[0]
    return None


def name(graph: Graph, term) -> str:
    return clean(one(graph, term, SKOS.prefLabel, RDFS.label) or local(term))


def short(graph: Graph, term) -> str:
    return re.sub(r"\s+(motif|risk pattern)$", "", name(graph, term), flags=re.I)


def names(graph: Graph, terms) -> str:
    return ", ".join(sorted(short(graph, term) for term in terms)) or "none"


def members(graph: Graph, kind) -> list:
    return sorted(set(graph.subjects(RDF.type, kind)), key=str)


def grouped(graph: Graph, items, predicate) -> dict:
    groups = defaultdict(list)
    for item in items:
        groups[one(graph, item, predicate)].append(item)
    return groups


def table(head: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    return lines + ["| " + " | ".join(row) + " |" for row in rows]


def motif_section(g: Graph, motifs: list) -> list[str]:
    out = ["## 1. Motifs", "", MOTIF_NOTE]
    families = grouped(g, motifs, PAIR.motifFamily)
    for family in sorted(families, key=lambda f: name(g, f)):
        out += [f"### {name(g, family)} ({len(families[family])})", ""]
        by_group = grouped(g, families[family], PAIR.motifGroup)
        for group in sorted(by_group, key=lambda f: name(g, f)):
            rows = []
            for motif in sorted(by_group[group], key=lambda m: name(g, m)):
                rows.append([
                    f"**{short(g, motif)}**<br>`pat:{local(motif)}`",
                    clean(one(g, motif, DCTERMS.description) or ""),
                    names(g, g.objects(motif, PAIR.hasRiskPattern)),
                    names(g, g.subjects(PAIR.realizedByMotif, motif)),
                ])
            out += [f"#### {name(g, group)}", ""]
            out += table(["Motif", "Recognises", "Carries", "Realizes"], rows) + [""]
    return out


def reads_any_match(g: Graph, risk_pattern) -> bool:
    """True where a risk query leaves the motif open and binds no pattern node."""
    path = Path(str(one(g, one(g, risk_pattern, PAIR.implementedBy), PAIR.implementationPath)))
    query = (REPO_ROOT / path).read_text(encoding="utf-8")
    return "pair:matchesMotif ?" in query and "bindsPatternNode pat:" not in query


def undetected_entries(g: Graph, risk_patterns: list) -> list[str]:
    cited = {o for rp in risk_patterns for p in (PAIR.derivedFrom, PAIR.mayIndicateRisk) for o in g.objects(rp, p)}
    return sorted(local(e) for e in members(g, NEXUS.Risk) if "owasp-asi#asi" in str(e) and e not in cited)


def risk_section(g: Graph, risk_patterns: list) -> list[str]:
    out = ["## 2. AI risk patterns", "", RISK_NOTE]
    families = grouped(g, risk_patterns, PAIR.riskPatternFamily)
    for family in sorted(families, key=lambda f: name(g, f)):
        rows = []
        for rp in sorted(families[family], key=lambda r: name(g, r)):
            conditions = sorted(clean(name(g, c)) for c in g.objects(rp, PAIR.hasApplicabilityCondition))
            motifs = list(g.objects(rp, PAIR.hasMotif))
            rows.append([
                f"**{short(g, rp)}**<br>`pat:{local(rp)}`",
                "; ".join(conditions) or clean(one(g, rp, DCTERMS.description) or ""),
                names(g, motifs) if motifs else "*names no motif*",
                ", ".join(sorted(f"`{local(o)}`" for o in g.objects(rp, PAIR.derivedFrom))),
                names(g, g.objects(rp, PAIR.suggestedControl)),
            ])
        out += [f"### {name(g, family)} ({len(families[family])})", ""]
        out += table(["Risk pattern", "Raised when", "Declared motifs", "Derived from", "Suggested controls"], rows) + [""]

    open_queries = [rp for rp in risk_patterns if reads_any_match(g, rp)]
    out += [
        "### Declared motifs and what raises a finding",
        "",
        "The motifs declared on a risk pattern are the structures the library curates for it.",
        "Most risk queries bind declared pattern nodes, so only those motifs can raise them.",
        "These read roles on any motif match, so a finding can name a motif that is not",
        f"declared on the risk pattern: {names(g, open_queries)}.",
        "",
    ]
    if undetected := undetected_entries(g, risk_patterns):
        entries = ", ".join(f"`{entry}`" for entry in undetected)
        out += [
            f"**Catalogued, not detected:** {entries}. An OWASP agentic entry gets a risk pattern only",
            "when it has a structural signature at design time.",
            "",
        ]
    return out + ["Every finding is a candidate: a structural disposition, never a confirmed failure.", ""]


def category_of(g: Graph, role, categories: set, seen=None):
    seen = seen if seen is not None else set()
    for parent in sorted(g.objects(role, PAIR.subRoleOf), key=str):
        if parent in seen:
            continue
        seen.add(parent)
        if parent in categories:
            return parent
        if found := category_of(g, parent, categories, seen):
            return found
    return None


def role_row(g: Graph, role, categories: set) -> list[str]:
    parents = [local(p) for p in sorted(g.objects(role, PAIR.subRoleOf), key=str) if p not in categories]
    return [
        f"`{local(role)}`",
        name(g, role),
        clean(one(g, role, SKOS.definition) or ""),
        ", ".join(f"`{p}`" for p in parents) or "",
    ]


def role_section(g: Graph, roles: list, categories: list) -> list[str]:
    category_set = set(categories)
    filed = defaultdict(list)
    for role in roles:
        if role not in category_set:
            filed[category_of(g, role, category_set)].append(role)

    head = ["Role", "Shown as", "Definition", "Refines"]
    out = [f"## 3. Annotation roles ({len(roles) - len(categories)} roles, {len(categories)} categories)", "", ROLE_NOTE]
    if filed[None]:
        rows = [role_row(g, r, category_set) for r in sorted(filed[None], key=local)]
        out += ["### Above the categories", ""] + table(head, rows) + [""]
    for category in sorted(categories, key=lambda c: name(g, c)):
        rows = [role_row(g, r, category_set) for r in sorted(filed[category], key=local)]
        out += [f"### {name(g, category)} ({len(rows)})", "", clean(one(g, category, SKOS.definition) or ""), ""]
        out += table(head, rows) + [""]
    return out


def data_section(g: Graph) -> list[str]:
    rows = []
    for category in members(g, PAIR.DataCategory):
        parent = one(g, category, PAIR.subDataCategoryOf)
        rows.append([
            f"`{local(category)}`",
            clean(one(g, category, SKOS.definition) or ""),
            f"`{local(parent)}`" if parent else "",
        ])
    derivations = []
    for implementation in members(g, PAIR.PatternImplementation):
        if one(g, implementation, PAIR.producesOutputType) == PAIR.DataCategoryPropagation:
            path = Path(str(one(g, implementation, PAIR.implementationPath)))
            derivations.append([f"`{path.name}`", name(g, implementation)])

    categories = len(rows)
    out = [f"## 4. Data categories ({categories})", "", CATEGORY_NOTE]
    out += table(["Category", "Definition", "Refines"], rows) + ["", "### Propagation rules", ""]
    return out + table(["Query", "What it derives"], sorted(derivations)) + [""]


def guidance_section() -> list[str]:
    graph = Graph().parse(GUIDANCE)
    rows = []
    for shape in members(graph, SH.NodeShape):
        messages = {clean(m) for m in graph.objects(shape, SH.message)}
        for node in list(graph.objects(shape, SH.sparql)) + list(graph.objects(shape, SH.property)):
            messages |= {clean(m) for m in graph.objects(node, SH.message)}
        severity = local(one(graph, shape, SH.severity) or SH.Violation)
        rows.append([f"`{local(shape)}`", severity, " ".join(sorted(messages))])
    return ["## 5. Annotation guidance (SHACL)", "", GUIDANCE_NOTE] + table(["Shape", "Severity", "Message"], rows) + [""]


def business_section() -> list[str]:
    graph = Graph().parse(BUSINESS)
    terms = []
    for kind in (OWL.ObjectProperty, OWL.DatatypeProperty, OWL.Class):
        for term in members(graph, kind):
            if isinstance(term, URIRef) and str(term).startswith(str(PAIR)):
                terms.append([f"`pair:{local(term)}`", clean(one(graph, term, RDFS.comment) or name(graph, term))])
    options = []
    for option in sorted(graph.subjects(RDF.type, PAIR.DataClassificationOption), key=lambda o: name(graph, o)):
        personal = one(graph, option, PAIR.meansPersonalData)
        bridged = "yes" if personal is None or personal.toPython() else "no"
        options.append([f"`{local(one(graph, option, PAIR.classifiesAs))}`", name(graph, option), bridged])

    out = ["## 6. Business context vocabulary", "", BUSINESS_NOTE]
    out += table(["Term", "What it does"], sorted(terms)) + ["", "### Data classifications an analyst can state", ""]
    return out + table(["DPV value", "Shown as", "Reaches the architecture as sensitive"], options) + [""]


def main() -> int:
    g = load_base_graph()
    motifs = members(g, PAIR.GraphMotif)
    risk_patterns = members(g, PAIR.RiskPattern)
    roles = members(g, PAIR.PatternRole)
    categories = members(g, PAIR.RoleCategory)
    controls = set(g.objects(None, PAIR.suggestedControl))
    counts = (
        f"**{len(motifs)} motifs**, **{len(risk_patterns)} AI risk patterns**, **{len(controls)} controls**, "
        f"**{len(roles) - len(categories)} roles** filed under **{len(categories)} categories**, and "
        f"**{len(members(g, PAIR.DataCategory))} data categories**."
    )
    lines = INTRO.format(counts=counts).splitlines() + [""]
    lines += motif_section(g, motifs) + risk_section(g, risk_patterns) + role_section(g, roles, categories)
    lines += data_section(g) + guidance_section() + business_section() + SEE_ALSO.splitlines()
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TARGET.name}: {counts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

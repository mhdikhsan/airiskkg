INTRO = """\
# PAIR-AI Catalogue: Motifs, AI Risk Patterns and Annotation Roles

> Generated by `python/scripts/generate_catalogue.py` from the loaded knowledge base.
> Do not edit this file: change the ontology or the generator and regenerate.
> `test_generated_documents.py` fails when the two differ.

Terminology follows [PAIR-AI_glossary_v1_4.md](PAIR-AI_glossary_v1_4.md).

{counts}

## How the three fit together

- **Roles** annotate elements. `pair:playsRole` goes on one BEAM element, and an
  element may carry several roles.
- **Motifs** are the structure a risk pattern reads: role-tagged elements and the
  `beam:use` / `beam:produce` edges between them. A motif is structure only: it makes no
  risk claim, and the AI risk patterns that read it do.
- **AI risk patterns** raise a **candidate risk finding** when a motif match also
  satisfies their applicability conditions. A finding requires triage and is never
  a confirmed defect.

Annotation is per element, and recognition is per combination: a motif matches only
when several correctly tagged elements are wired together in the expected shape.

- **Motifs nest.** A smaller motif can be a subgraph of a larger one and co-matches
  with it, so match counts measure structural coverage and not how many distinct
  things a system does.
- **Motifs cannot express absence.** Matching is monotone, so every "without" or
  "only" claim lives in an applicability condition (glossary R9).
- **Process typing does not decide a match.** Step nodes match on
  `a/rdfs:subClassOf* beam:Process`, so the role is what selects a step.
"""

MOTIF_NOTE = """\
Motifs are shelved by `pair:motifFamily` and `pair:motifGroup`, a filing decision
about this library that no match query reads. **Carries** lists the risk patterns
declared on the motif. **Realizes** lists the controls it is a candidate structure
for, which is not proof that adding it removes the risk: several realizing motifs
carry risks of their own, so an amended architecture has to be assessed again.
"""

RISK_NOTE = """\
Risk Pattern = Motif + Applicability Conditions + Mechanism + Taxonomy Links +
Controls. **Raised when** lists the applicability conditions; every absence they
name is relative to the submitted graph (R4), so a finding says no control is
represented, never that none exists.
"""

ROLE_NOTE = """\
Assign with `pair:playsRole`. A motif that asks for a parent role also matches the
roles under it (`pair:subRoleOf*`), so a role parented to the wrong abstraction is
inert: tagging an element with it silently prevents the match. Categories file the
roles and no query names one. **Shown as** is the name in the workbench picker.
"""

CATEGORY_NOTE = """\
Assign with `pair:containsDataCategory` on a `beam:Data` element. This is the one
facet that is also derived: tag where protected or untrusted content enters, and the
propagation rules below work out where it can reach. There is no personal data
category, deliberately. Personal data is expressed with DPV concepts through
`facet:hasPersonalDataCategory` (glossary R3).
"""

GUIDANCE_NOTE = """\
`shacl/annotation_guidance.ttl` asks whether an annotation will actually match
anything. Every shape is `sh:Info` or `sh:Warning`, so it cannot change whether a
graph conforms.
"""

BUSINESS_NOTE = """\
A submitted document may carry a business process model (sBPMN 2.0) beside the
architecture. It joins by refinement and never by subsumption: a `bpmn:activity` is
not a `beam:Process`. What a process states about its data reaches the architecture
through `business_data_bridge.rq`, which marks the edge of the refined system and
leaves the rest to propagation.
"""

